"""
build_vector_index.py

Builds embeddings and a FAISS vector index from chunks_final.jsonl,
using the fine-tuned embedding model trained on our health dataset
instead of the public base model.

Usage:
    python3 build_vector_index.py

Output:
    data/processed/vector_index.faiss
    data/processed/vector_metadata.json
"""

import json
from pathlib import Path

import numpy as np
import faiss
from sentence_transformers import SentenceTransformer
from tqdm import tqdm


PROCESSED_DIR = Path(__file__).parent.parent / "data" / "processed"
CHUNKS_PATH = PROCESSED_DIR / "chunks_final.jsonl"
INDEX_PATH = PROCESSED_DIR / "vector_index.faiss"
METADATA_PATH = PROCESSED_DIR / "vector_metadata.json"

# Fine-tuned embedding model (local, not loaded from the Hub).
# Generated by finetune_embedding.py.
EMBEDDING_MODEL_NAME = str(
    Path(__file__).parent.parent
    / "backend"
    / "models_cache"
    / "finetuned-embedding-health"
)

BATCH_SIZE = 64


def load_chunks():
    if not CHUNKS_PATH.exists():
        raise FileNotFoundError(
            f"{CHUNKS_PATH} not found. Run merge_datasets.py first."
        )

    with CHUNKS_PATH.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def main():
    chunks = load_chunks()
    print(f"Total number of chunks for embedding: {len(chunks)}")

    print(f"Loading embedding model: {EMBEDDING_MODEL_NAME}")
    model = SentenceTransformer(EMBEDDING_MODEL_NAME)

    texts = [c["text"] for c in chunks]

    print("Generating embeddings (this may take some time depending on the number of chunks)...")
    embeddings = model.encode(
        texts,
        batch_size=BATCH_SIZE,
        show_progress_bar=True,
        convert_to_numpy=True,
        normalize_embeddings=True,
    )

    embeddings = np.asarray(embeddings, dtype="float32")

    dimension = embeddings.shape[1]
    print(f"Embedding vector dimension: {dimension}")

    index = faiss.IndexFlatIP(dimension)
    index.add(embeddings)

    faiss.write_index(index, str(INDEX_PATH))
    print(f"FAISS index saved to: {INDEX_PATH}")

    metadata = [
        {
            "id": c["id"],
            "text": c["text"],
            "source": c.get("source", ""),
            "topic": c.get("topic", ""),
            "subtopic": c.get("subtopic", ""),
            "language": c.get("language", ""),
            "difficulty": c.get("difficulty", ""),
            "url": c.get("url", ""),
        }
        for c in chunks
    ]

    with METADATA_PATH.open("w", encoding="utf-8") as f:
        json.dump(metadata, f, ensure_ascii=False)

    print(f"Metadata saved to: {METADATA_PATH}")

    print(
        "\nDone. The Retriever can now load this index for semantic search."
    )


if __name__ == "__main__":
    main()